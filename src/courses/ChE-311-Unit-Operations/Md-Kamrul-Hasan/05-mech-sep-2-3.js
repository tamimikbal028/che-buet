      <section class="topic-section" id="topic-5" data-topic="5" data-short="Electrostatic Precipitation (ESP)">
      <h2 class="section-title">
        5. Electrostatic Precipitation (ESP): Principles, Mechanism &amp; Re-entrainment
      </h2>

      <h3 class="sub-title">
        Electrostatic Precipitation
        <span class="slide-tag">Slides 19, 20</span>
      </h3>
      <p>
        Electrostatic precipitation (ESP) is defined as the use of
        <strong>electrostatic forces to remove charged solid particles or liquid droplets from gas streams</strong>
      </p>
      <p style="margin-bottom: 4px">
        The essential components of the electrode system consist of:
      </p>
      <ul>
        <li>One or more corona discharge electrodes (&lsquo;-&rsquo; polarity) of relatively small diameter (such as wires)</li>
        <li>Collecting electrodes (&lsquo;+&rsquo; polarity) (such as plates or tubes).</li>
      </ul>
      <p>
        The electrical mechanisms for the precipitation of particles or droplets are provided by discharge electrodes, which charge the particles or droplets in a corona discharge and create the electrostatic field that causes the charged particles or droplets to migrate toward the collecting electrodes.
      </p>

      <div class="grid-2">
        <div class="card">
          <h4>A. Advantages</h4>
          <ol style="margin-bottom: 0">
            <li>High removal efficiency of fine particles/droplets</li>
            <li>Handling of large gas volumes with low pressure drop</li>
            <li>Collection of either dry powder materials or wet fumes/mists</li>
            <li>Sustenance of a wide range of gas temperature up to approx 700&deg;C</li>
            <li>Low operating costs, except at very high removal efficiencies</li>
          </ol>
        </div>
        <div class="card">
          <h4>B. Disadvantages</h4>
          <ol style="margin-bottom: 0">
            <li>High capital costs</li>
            <li>Unable to collect gaseous pollutants</li>
            <li>Large space requirement</li>
            <li>Inflexibility of operating conditions</li>
            <li>Variation of removal efficiency with particle/droplet properties</li>
          </ol>
        </div>
      </div>

      <ul>
        <li>
          An <strong>electrostatic precipitator (ESP) is</strong> an device that removes dust particles from a flowing gas (such as air) using the force of an induced <strong>electrostatic attraction</strong>
        </li>
        <li>
          Electrostatic precipitators are highly efficient filtration devices that can easily remove <strong>fine particulate matter</strong> such as dust and smoke from the air stream.
        </li>
      </ul>
      <div class="fig-box">
        <strong>Slide 20: Electrostatic Precipitators (ESPs) — Electrical field, charged particles, collections plates &amp; electrodes</strong><br />
        <img src="{{SLIDES}}/slide_20.png" alt="Slide 20 - Electrostatic Precipitators diagrams" style="width:94%; margin:6px auto 0 auto;" />
      </div>

      <h3 class="sub-title">
        Separation Mechanism
        <span class="slide-tag">Slide 21</span>
      </h3>
      <ul>
        <li>
          <strong>Discharge electrode :</strong> Electrodes wire which carries negatively charged high voltage (<strong>between 20 to 80KV</strong>) act as discharge or emitting electrodes.
        </li>
        <li>
          <strong>Collector electrode :-</strong> Electrode wire which carries positively charged high voltage act as Collecting electrodes.
        </li>
      </ul>
      <div class="fig-box">
        <strong>Slide 21: Separation Mechanism — Discharge electrode, Collector electrodes &amp; negative gas ion charging</strong><br />
        <img src="{{SLIDES}}/slide_21.png" alt="Slide 21 - Separation Mechanism diagrams" style="width:92%; margin:6px auto 0 auto;" />
      </div>

      <h3 class="sub-title">
        Particle Charging, Transportation &amp; Removal
        <span class="slide-tag">Slide 22</span>
      </h3>
      <p style="margin-bottom: 4px"><strong>Particle Charging:</strong> Particle-charging are two types:</p>
      <ol>
        <li>
          <strong>field charging</strong>, also known <strong>as impact charging or ion bombardment</strong>, wherein particles are bombarded by ions moving under the influence of the applied electric field,
        </li>
        <li>
          <strong>diffusion charging</strong>, wherein particles are charged as a result of the motion of the ions produced by the <strong>thermal motion</strong> of surrounding gas molecules.
        </li>
      </ol>
      <p>
        The <strong>field-charging mechanism predominates for particles larger than 0.5 &mu;m</strong>, whereas the <strong>diffusion-charging mechanism predominates for particles smaller than 0.1 &mu;m</strong>.
      </p>
      <div class="grid-2">
        <div class="card">
          <h4>Transportation of charged particles</h4>
          <p style="margin-bottom: 0">
            The charged particles, in turn, being under the influence of the high potential difference maintained between the discharge and collecting electrodes, are attracted to the collecting electrodes and thus are separated from the gas stream.
          </p>
        </div>
        <div class="card">
          <h4>Removal of particles</h4>
          <p style="margin-bottom: 0">
            Solid particles build up a layer on the collecting surface, from which the accumulated deposit has to be periodically removed by scrapping or flushing, and are allowed to collect into a hopper.
          </p>
        </div>
      </div>

      <h3 class="sub-title">
        Particle Re-entrainment
        <span class="slide-tag">Slide 23</span>
      </h3>
      <p style="margin-bottom: 6px">Re-entrainment may occur as a result of</p>
      <ol>
        <li>
          <strong>Low particle resistivity</strong>
          <p style="margin: 4px 0 8px 0">
            The dominant force holding particles on the collecting surface results from the flow of current through the particles; <strong>if the particle resistivity is too low, not enough charge is retained by the particle.</strong> In this case, the negative charge may leak off the particle, which in turn, acquires a positive charge from the collecting electrode and is forcefully accelerated away from that electrode.
          </p>
          <p style="margin: 0 0 8px 0">
            <strong>Large fly ash particles and carbon black particles exhibit low resistivity</strong>. In the case <strong>of fly ash, the re-entrainment problem can be reduced by using high-efficiency cyclones preceding the electrostatic precipitator</strong>. <strong>Carbon black particles are too small to be separated by cyclones; nevertheless, the electrostatic precipitator helps to agglomerate the carbon particles into coarser particles, which then can be removed by cyclones that follow the electrostatic precipitator.</strong>
          </p>
        </li>
        <li>
          <strong>Erosion of the particle from collecting electrodes</strong>
          <p style="margin: 4px 0 8px 0">
            Non-uniform gas velocity can result in excessively high gas velocity through some sections of the electrostatic precipitator. The excessive turbulence from such high velocities produces re-entrainment of the collected particles on the electrodes owing to the scouring action of the gas.
          </p>
          <p style="margin: 0">
            By providing (1) <strong>baffles to shield deposited particles</strong> from the re-entraining forces of the gas stream, (2) <strong>catch pockets</strong> that convey precipitated particles into a quiescent gas zone behind the collecting electrode, erosion problem can be minimized.
          </p>
        </li>
      </ol>
      </section>

