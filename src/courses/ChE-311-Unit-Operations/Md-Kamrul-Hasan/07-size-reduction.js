      <h3 class="sub-title">
        3.3 Applicability of Laws &amp; Energy Consumption vs. Product Size
        <span class="slide-tag">Slides 16, 17</span>
      </h3>
      <ul>
        <li><strong>Rittinger&rsquo;s law</strong> holds most accurately for <strong>fine grinding over the range 10&ndash;1000 &mu;m</strong>, where new surface creation per unit mass is large.</li>
